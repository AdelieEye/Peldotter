function love.conf(t)
    t.identity = "Peldotter"
    t.version  = "11.5"
    t.console  = false

    t.window.title      = "Peldotter"
    t.window.width      = 1920
    t.window.height     = 1080
    t.window.resizable  = true
    t.window.borderless = true
    t.window.fullscreen = true
    t.window.vsync      = 1
end
